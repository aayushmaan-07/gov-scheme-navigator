/**
 * Returns fresh discovered schemes from the PIB crawler pool.
 * It strictly filters out any scheme that:
 * 1. Already exists in the portal's active database (SCHEMES_DATABASE)
 * 2. Has already been approved (approvedSchemes)
 * 3. Is already sitting in the pending queue (existingPending)
 * 
 * If all schemes in the pool have been discovered, it returns [] (EMPTY ARRAY)
 * so that the system correctly informs the user that all available schemes
 * have been ingested!
 */
export function getFreshDiscoveredSchemes(
  existingPending: PendingScheme[],
  approvedSchemes: Scheme[] = []
): PendingScheme[] {
  // 1. Gather all existing IDs
  const allKnownIds = new Set<string>([
    ...SCHEMES_DATABASE.map((s) => s.id),
    ...approvedSchemes.map((s) => s.id),
    ...existingPending.map((s) => s.id),
  ]);

  // 2. Also match by normalized scheme name so no existing scheme is ever re-discovered
  const allKnownNames = new Set<string>([
    ...SCHEMES_DATABASE.map((s) => s.name.toLowerCase().trim()),
    ...approvedSchemes.map((s) => s.name.toLowerCase().trim()),
    ...existingPending.map((s) => s.name.toLowerCase().trim()),
  ]);

  // Filter out any scheme that already exists anywhere
  const available = CRAWLABLE_PIB_SCHEMES.filter(
    (s) => !allKnownIds.has(s.id) && !allKnownNames.has(s.name.toLowerCase().trim())
  );

  // If NO schemes are left, return empty array as requested by user
  if (available.length === 0) {
    return [];
  }

  // Return at most 2 distinct schemes
  return available.slice(0, 2).map((s) => ({
    ...s,
    discoveredAt: 'Just now (Live PIB Crawler)',
    status: 'pending_review',
  }));
}
